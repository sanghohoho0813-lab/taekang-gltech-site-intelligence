/** 역할별로 보이는 매뉴얼 (본사는 교육용으로 전부) */
export function manualsFor(role: RoleId): Manual[] {
  if (role === "field") return MANUALS.filter((m) => m.id === "field" || m.id === "faq");
  if (role === "partner") return MANUALS.filter((m) => m.id === "partner");
  return MANUALS;
}

/** ‘버튼 이름’ 목록 — 화면 코드에 실제로 있는지 테스트에서 확인 */
export function quotedLabels(m: Manual): string[] {
  const out = new Set<string>();
  for (const s of m.sections) for (const st of s.steps) for (const x of `${st.t} ${st.d ?? ""}`.matchAll(/‘([^’]+)’/g)) out.add(x[1]);
  return [...out];
}
