// DEMO_SCRIPT.md 큐시트 순서대로 PC+Mobile 화면을 조작하고, 큐시트에 적힌 숫자가 화면에 실제로 있는지 검증
// 사용: npm run build && npm start (또는 다른 포트) → QA_BASE_URL=http://127.0.0.1:3000 npm run qa:cuesheet
import { chromium } from "@playwright/test";
const B = process.env.QA_BASE_URL ?? "http://127.0.0.1:3000";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "ko-KR", timezoneId: "Asia/Seoul" });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message)); page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
const results = []; const t0 = Date.now();
const check = (step, label, text, needles) => { for (const n of needles) { const ok = n instanceof RegExp ? n.test(text) : text.includes(n); results.push([step, label, String(n), ok]); } };
const txt = (loc) => loc.innerText();
await page.goto(B + "/dashboard");
await page.evaluate(() => { localStorage.clear(); localStorage.setItem("tk-site-intel:prefs:v1", JSON.stringify({ theme: "onyx-gold", fontScale: "md", reduceMotion: false, role: "ceo", deviceView: "pc", mobilePersona: "same", tutorialDone: true })); });
await page.goto(B + "/dashboard"); await page.getByTestId("kpi-strip").waitFor();
await page.waitForTimeout(1200);
const kpi = await txt(page.getByTestId("kpi-strip"));
check("0:00", "대시보드 KPI", kpi, ["3곳", "30.7억", "3.96억", "12.9%", "4.5억"]);
check("0:00", "위험 알림 배지", await txt(page.getByTestId("nav-insights")), ["3"]);
console.log("KPI:", kpi.replace(/\n/g, " | "));
await page.getByTestId("site-row-site-a").click();
await page.getByTestId("m-contract").waitFor(); await page.waitForTimeout(900);
const eng = await txt(page.locator('[data-tour="profit-engine"]'));
check("0:30", "A현장 손익 엔진", eng, ["10억 원", "8.5억 원", "1.5억 원", "15%", "5.1억", "3.4억"]);
await page.getByTestId("device-dual").click();
const persona = page.getByTestId("mobile-persona");
await persona.selectOption("field");
const f = page.frameLocator('[data-testid="device-frame"]');
await f.getByTestId("open-report-sheet").click();
await f.getByTestId("fill-demo").click();
const sheetText = await f.getByTestId("report-sheet").innerText();
const vals = await f.locator('[data-testid="report-sheet"] input').evaluateAll((els) => els.map((e) => e.value).filter(Boolean));
check("1:00", "모바일 입력값", vals.join(" "), ["30,000,000", "10,000,000"]);
await f.getByTestId("submit-report").click();
await f.getByTestId("report-done").waitFor();
const done = await f.getByTestId("report-done").innerText();
check("1:00", "모바일 등록 완료", done, ["4,000만"]);
results.push(["1:00", "현장직원 완료 화면에 이익률·이익 수치 없음", "no %·억", !/\d+(\.\d+)?%|\d+(\.\d+)?억/.test(done)]);
console.log("DONE:", done.replace(/\n/g, " | "));
await page.waitForTimeout(1500);
const eng2 = await txt(page.locator('[data-tour="profit-engine"]'));
check("1:45", "PC 손익 재계산", eng2, ["8.9억 원", "1.1억 원", "11%", "4,000만", /−4%p/]);
const pageText = await page.locator("main").first().innerText();
check("1:45", "자재비 초과", pageText, ["+7.9%"]);
check("1:45", "위험 배지 6", await txt(page.getByTestId("nav-insights")), ["6"]);
await page.getByTestId("nav-insights").click();
const board = page.getByTestId("signal-board"); await board.waitFor(); await page.waitForTimeout(600);
const siteASignals = await board.locator("[data-rule]").filter({ hasText: "A현장" }).count();
results.push(["2:05", "A현장 신호 3건", "3", siteASignals === 3]);
const unb = board.locator('[data-rule="UNBILLED_CHANGE"]');
check("2:05", "설계변경 신호", await unb.innerText(), ["4,000만"]);
await unb.getByTestId("create-action").click();
const mv = await page.getByTestId("assign-modal").locator("input, textarea").evaluateAll((els) => els.map((e) => e.value).join(" "));
check("2:05", "조치 모달 제목", mv, ["추가공사 청구가능성 검토"]);
results.push(["2:05", "담당 기본값 최현장", "u-field", (await page.getByTestId("assignee-select").inputValue()) === "u-field"]);
await page.getByTestId("assign-confirm").click();
await f.getByTestId("action-card").filter({ hasText: "추가공사 청구가능성 검토" }).waitFor({ timeout: 5000 });
results.push(["2:05", "모바일에 배정 조치 즉시 표시", "visible", true]);
const card = page.getByTestId("action-board").getByTestId("action-card").filter({ hasText: "추가공사 청구가능성 검토" });
await card.getByTestId("action-start").click(); await page.waitForTimeout(300);
await card.getByTestId("action-complete").click();
const cm = page.getByTestId("complete-modal");
await cm.getByTestId("fill-result").click();
check("2:50", "완료 모달 청구 4,000만", await cm.innerText(), ["4,000"]);
await cm.getByTestId("complete-confirm").click(); await page.waitForTimeout(800);
check("2:50", "완료 카드", await card.innerText(), ["완료", /결과 확인|Proof/]);
await page.goto(B + "/sites/site-a"); await page.waitForTimeout(1200);
const eng3 = await txt(page.locator('[data-tour="profit-engine"]'));
check("2:50", "승인 전 변경공사 미반영 + 시뮬레이션", eng3, ["4,000만", "14.4%", "11%"]);
await page.getByTestId("device-pc").click();
await page.getByTestId("nav-report").click(); await page.getByTestId("report-summary").waitFor(); await page.waitForTimeout(900);
const rep = await txt(page.getByTestId("report-summary"));
check("3:15", "대표 보고서", rep, ["3.96억", "3.56억", "4,000만", "15% → 11%", "5건", "확인 1"]);
console.log("REPORT:", rep.replace(/\n/g, " | ").slice(0, 600));
await page.getByTestId("demo-reset").click(); await page.getByTestId("reset-confirm").click(); await page.waitForTimeout(800);
await page.goto(B + "/sites/site-a"); await page.waitForTimeout(1200);
check("3:45", "초기화 후 복구", await txt(page.locator('[data-tour="profit-engine"]')), ["10억 원", "8.5억 원", "1.5억 원", "15%"]);
const fail = results.filter((r) => !r[3]);
for (const r of results) console.log(r[3] ? "PASS" : "FAIL", r[0], r[1], "::", r[2]);
console.log(`\n${results.length - fail.length}/${results.length} PASS · errors ${errs.length} · ${((Date.now() - t0) / 1000).toFixed(1)}s`, errs.slice(0, 3));
await browser.close();
process.exit(fail.length || errs.length ? 1 : 0);
